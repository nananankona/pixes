import 'package:uuid/uuid.dart';

/// Reports sync progress: phase label key, completed items, total items.
typedef SyncProgressCallback = void Function(String phase, int done, int total);

/*
-- Run this SQL in your Supabase SQL Editor:
create table if not exists sync_devices (
  device_id text primary key,
  device_name text not null default '',
  last_sync_at timestamp with time zone default timezone('utc'::text, now()),
  inserted_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);
create table if not exists sync_settings (
  id bigint generated by default as identity primary key,
  data jsonb,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  inserted_at timestamp with time zone default timezone('utc'::text, now()) not null
);
create table if not exists sync_search_history (
  id bigint generated by default as identity primary key,
  keyword text not null,
  search_type int not null,
  data jsonb,
  unique(keyword, search_type),
  inserted_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);
create table if not exists sync_browsing_history (
  id bigint generated by default as identity primary key,
  illust_id bigint not null,
  data jsonb,
  unique(illust_id),
  inserted_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);
-- If you get 401 errors, disable RLS on these tables:
alter table sync_devices disable row level security;
alter table sync_settings disable row level security;
alter table sync_search_history disable row level security;
alter table sync_browsing_history disable row level security;
-- Realtime delete sync needs full row data in DELETE events:
alter table sync_search_history replica identity full;
alter table sync_browsing_history replica identity full;
*/

class SyncService {
  static SyncService? _instance;
  factory SyncService() => _instance ??= SyncService._();
  SyncService._();

  Dio? _dio;
  Timer? _debounceTimer;
  Timer? _realtimePullTimer;
  int? lastStatusCode;
  bool _stopped = false;
  bool _pulling = false;
  bool _busy = false;
  bool _applyingRemote = false;

  /// True while the realtime channel is connected.
  ValueListenable<bool> get live => realtimeSync.connected;

  String? get _url => appdata.settings["syncUrl"] as String?;
  String? get _key => appdata.settings["syncKey"] as String?;

  bool get enabled {
    if (appdata.settings["syncEnabled"] != true) return false;
    final url = _url;
    final key = _key;
    return url != null && url.isNotEmpty && key != null && key.isNotEmpty;
  }

  bool get syncSettingsEnabled =>
      appdata.settings["syncSettingsEnabled"] != false;

  String? get projectId {
    final url = _url;
    if (url == null || url.isEmpty) return null;
    final u = url.replaceFirst('https://', '').replaceFirst('http://', '');
    final dot = u.indexOf('.');
    if (dot <= 0) return null;
    return u.substring(0, dot);
  }

  bool get needsSetup => lastStatusCode == 401 || lastStatusCode == 403;
  bool get stopped => _stopped;

  String get _deviceId {
    var id = appdata.settings["syncDeviceId"] as String?;
    if (id == null || id.isEmpty) {
      id = const Uuid().v4();
      appdata.settings["syncDeviceId"] = id;
      appdata.writeSettings();
    }
    return id;
  }

  String get deviceName =>
      appdata.settings["syncDeviceName"] as String? ?? "";

  void resetDeviceId() {
    appdata.settings["syncDeviceId"] = const Uuid().v4();
    appdata.writeSettings();
  }

  bool _ensureDio() {
    if (!enabled || _stopped) return false;
    if (_dio != null) return true;
    _dio = Dio(BaseOptions(
      baseUrl: "${_url!}/rest/v1/",
      headers: {
        'apikey': _key!,
        'Authorization': 'Bearer ${_key!}',
        'Content-Type': 'application/json',
        'Accept': 'application/json',
      },
      validateStatus: (_) => true,
      // Avoid hanging forever on a dead connection (was reported as UI freeze).
      connectTimeout: const Duration(seconds: 30),
      sendTimeout: const Duration(seconds: 30),
      receiveTimeout: const Duration(seconds: 60),
    ));
    return true;
  }

  void reconfigure() {
    _dio = null;
    _debounceTimer?.cancel();
    _debounceTimer = null;
    _realtimePullTimer?.cancel();
    _realtimePullTimer = null;
    realtimeSync.stop();
    _stopped = false;
  }

  void init() {
    if (!enabled) return;
    if (!_ensureDio()) return;
    _pullAll();
    _startRealtime();
  }

  void _startRealtime() {
    if (appdata.settings["syncRealtime"] == false) return;
    final url = _url;
    final key = _key;
    if (url == null || key == null) return;
    realtimeSync.start(
      supabaseUrl: url,
      apiKey: key,
      onEvent: _onRealtimeEvent,
    );
  }

  void _onRealtimeEvent(String table, String type,
      Map<String, dynamic> record, Map<String, dynamic>? oldRecord) {
    if (_stopped || !enabled) return;
    if (type == 'DELETE') {
      _applyRemoteDelete(table, record, oldRecord);
      return;
    }
    // Coalesce bursts of upserts into one pull (correct merge, no
    // per-row timestamp bookkeeping needed).
    _realtimePullTimer?.cancel();
    _realtimePullTimer = Timer(const Duration(seconds: 1), () {
      if (_stopped || !enabled || _pulling || _busy) return;
      _pullAll();
    });
  }

  void _applyRemoteDelete(String table, Map<String, dynamic> record,
      Map<String, dynamic>? oldRecord) {
    final row = oldRecord ?? record;
    _applyingRemote = true;
    try {
      if (table == 'sync_search_history') {
        final keyword = (row['keyword'] ?? '').toString();
        final searchType = int.tryParse('${row['search_type'] ?? -1}') ?? -1;
        if (keyword.isNotEmpty && searchType >= 0) {
          appdata.removeSearchHistory(keyword, searchType);
        }
      } else if (table == 'sync_browsing_history') {
        final id = int.tryParse('${row['illust_id'] ?? ''}');
        if (id != null) {
          HistoryManager().remove(id);
        }
      }
    } finally {
      _applyingRemote = false;
    }
  }

  /// Delete all remote search history rows (used when clearing locally).
  Future<void> deleteRemoteSearchHistory() async {
    if (!_ensureDio()) return;
    try {
      final res = await _dio!.delete('/sync_search_history');
      if (!_ok(res)) {
        Log.error("Sync", "Delete remote search history failed: ${res.statusCode}");
      }
    } catch (e) {
      Log.error("Sync", "Delete remote search history failed: $e");
    }
  }

  /// Delete one remote search history row.
  Future<void> deleteRemoteSearchRow(String keyword, int searchType) async {
    if (!_ensureDio()) return;
    try {
      final res = await _dio!.delete('/sync_search_history',
          queryParameters: {'keyword': 'eq.$keyword', 'search_type': 'eq.$searchType'});
      if (!_ok(res)) {
        Log.error("Sync", "Delete remote search row failed: ${res.statusCode}");
      }
    } catch (e) {
      Log.error("Sync", "Delete remote search row failed: $e");
    }
  }

  /// Delete all remote browsing history rows (used when clearing locally).
  Future<void> deleteRemoteBrowsingHistory() async {
    if (!_ensureDio()) return;
    try {
      final res = await _dio!.delete('/sync_browsing_history');
      if (!_ok(res)) {
        Log.error("Sync", "Delete remote browsing history failed: ${res.statusCode}");
      }
    } catch (e) {
      Log.error("Sync", "Delete remote browsing history failed: $e");
    }
  }

  void notifyChange() {
    if (!enabled) return;
    if (_stopped) return;
    if (_pulling || _busy || _applyingRemote) return;
    _debounceTimer?.cancel();
    _debounceTimer = Timer(const Duration(seconds: 2), _pushAll);
  }

  bool _ok(Response r) {
    lastStatusCode = r.statusCode;
    if (r.statusCode == 401 || r.statusCode == 403) {
      _stopped = true;
      Log.error("Sync", "Stopped due to HTTP ${r.statusCode}");
    }
    return r.statusCode != null && r.statusCode! >= 200 && r.statusCode! < 300;
  }

  Future<void> _pullAll({SyncProgressCallback? onProgress}) async {
    if (!_ensureDio()) return;
    _pulling = true;
    try {
      final futures = <Future<void>>[];
      futures.add(_pullSearchHistory(onProgress));
      futures.add(_pullBrowsingHistory(onProgress));
      if (syncSettingsEnabled) futures.add(_pullSettings(onProgress));
      await Future.wait(futures);
      await _upsertDevice();
    } finally {
      _pulling = false;
    }
  }

  Future<void> _pushAll({SyncProgressCallback? onProgress}) async {
    if (!_ensureDio()) return;
    final futures = <Future<void>>[];
    futures.add(_pushSearchHistory(onProgress));
    futures.add(_pushBrowsingHistory(onProgress));
    if (syncSettingsEnabled) futures.add(_pushSettings(onProgress));
    await Future.wait(futures);
    await _upsertDevice();
  }

  Future<String?> syncNow({SyncProgressCallback? onProgress}) async {
    if (!_ensureDio()) return "Sync not configured";
    _stopped = false;
    if (_busy) return "Sync already running";
    _busy = true;
    try {
      await _pushAll(onProgress: onProgress);
      await _pullAll(onProgress: onProgress);
    } catch (e) {
      Log.error("Sync", "syncNow failed: $e");
      return e.toString();
    } finally {
      _busy = false;
    }
    return null;
  }

  Future<int?> checkConnection() async {
    if (!_ensureDio()) {
      _stopped = false;
      return null;
    }
    _stopped = false;
    try {
      final res = await _dio!.get('/sync_devices?select=device_id&limit=1');
      lastStatusCode = res.statusCode;
      return res.statusCode;
    } catch (_) {
      return null;
    }
  }

  Future<void> _pullSettings([SyncProgressCallback? onProgress]) async {
    if (!syncSettingsEnabled || _stopped) return;
    final res = await _dio!.get('/sync_settings?select=data,updated_at&id=eq.1');
    if (!_ok(res) || res.data == null || (res.data as List).isEmpty) return;
    final row = (res.data as List)[0] as Map<String, dynamic>;
    final remoteData = row['data'] as Map<String, dynamic>;
    final remoteTime = DateTime.parse(row['updated_at'] as String);
    final localTimeStr = appdata.settings["syncSettingsUpdatedAt"] as String?;
    final localTime = localTimeStr != null ? DateTime.tryParse(localTimeStr) : null;
    if (localTime == null || remoteTime.isAfter(localTime)) {
      for (var key in remoteData.keys) {
        appdata.settings[key] = remoteData[key];
      }
      appdata.settings["syncSettingsUpdatedAt"] = remoteTime.toIso8601String();
      appdata.writeSettings();
    }
    onProgress?.call("Pulling settings", 1, 1);
  }

  Future<void> _pushSettings([SyncProgressCallback? onProgress]) async {
    if (!syncSettingsEnabled || _stopped) return;
    onProgress?.call("Pushing settings", 0, 1);
    final data = Map<String, dynamic>.from(appdata.settings);
    data.remove("syncKey");
    data.remove("syncUrl");
    data.remove("syncDeviceId");
    data.remove("syncDeviceName");
    data.remove("syncSettingsUpdatedAt");
    data.remove("syncEnabled");
    data.remove("syncSettingsEnabled");
    final now = DateTime.now().toIso8601String();
    appdata.settings["syncSettingsUpdatedAt"] = now;
    final res = await _dio!.post('/sync_settings', data: {
      'id': 1,
      'data': data,
      'updated_at': now,
    }, options: Options(headers: {'Prefer': 'resolution=merge-duplicates'}));
    if (!_ok(res)) {
      Log.error("Sync", "Push settings failed: ${res.statusCode} ${res.statusMessage}");
    }
    onProgress?.call("Pushing settings", 1, 1);
  }

  Future<void> _pullSearchHistory([SyncProgressCallback? onProgress]) async {
    if (_stopped) return;
    final res = await _dio!.get('/sync_search_history?select=data,keyword,search_type,updated_at');
    if (!_ok(res) || res.data == null) return;
    final remote = (res.data as List).map((e) {
      final row = e as Map<String, dynamic>;
      return (
        entry: SearchHistoryEntry.fromJson(row['data'] as Map<String, dynamic>),
        updatedAt: row['updated_at'] as String?
      );
    }).toList();
    final local = appdata.getSearchHistory();
    final seen = <String>{};
    final merged = <SearchHistoryEntry>[];
    for (var e in local) {
      seen.add("${e.keyword}:${e.searchType}");
      merged.add(e);
    }
    for (var r in remote) {
      final key = "${r.entry.keyword}:${r.entry.searchType}";
      if (!seen.contains(key)) {
        seen.add(key);
        merged.add(r.entry);
      }
    }
    appdata.importSearchHistory(merged, notify: false);
    onProgress?.call("Pulling search history", 1, 1);
  }

  Future<void> _pushSearchHistory([SyncProgressCallback? onProgress]) async {
    if (_stopped) return;
    final local = appdata.getSearchHistory();
    final now = DateTime.now().toIso8601String();
    onProgress?.call("Pushing search history", 0, local.length);
    for (var i = 0; i < local.length; i++) {
      final entry = local[i];
      final res = await _dio!.post('/sync_search_history?on_conflict=keyword,search_type', data: {
        'keyword': entry.keyword,
        'search_type': entry.searchType,
        'data': entry.toJson(),
        'updated_at': now,
      }, options: Options(headers: {'Prefer': 'resolution=merge-duplicates'}));
      if (!_ok(res)) {
        Log.error("Sync", "Push search history failed: ${res.statusCode}");
        continue;
      }
      onProgress?.call("Pushing search history", i + 1, local.length);
    }
  }

  Future<void> _pullBrowsingHistory([SyncProgressCallback? onProgress]) async {
    if (_stopped) return;
    final res = await _dio!.get('/sync_browsing_history?select=data,illust_id,updated_at');
    if (!_ok(res) || res.data == null) return;
    final remote = (res.data as List).map((e) {
      final d = (e as Map<String, dynamic>)['data'] as Map<String, dynamic>;
      return IllustHistory(
        d['id'] as int,
        d['imgPath'] as String,
        DateTime.parse(d['time'] as String),
        d['imageCount'] as int,
        (d['isR18'] as num) == 1,
        (d['isR18G'] as num) == 1,
        (d['isAi'] as num) == 1,
        (d['isGif'] as num) == 1,
        d['width'] as int,
        d['height'] as int,
      );
    }).toList();
    final local = HistoryManager().getAll();
    final map = <int, IllustHistory>{};
    for (var e in local) { map[e.id] = e; }
    for (var e in remote) { map[e.id] = e; }
    HistoryManager().importAll(map.values.toList());
    onProgress?.call("Pulling browsing history", 1, 1);
  }

  Future<void> _pushBrowsingHistory([SyncProgressCallback? onProgress]) async {
    if (_stopped) return;
    final local = HistoryManager().getAll();
    final now = DateTime.now().toIso8601String();
    onProgress?.call("Pushing browsing history", 0, local.length);
    for (var i = 0; i < local.length; i++) {
      final h = local[i];
      final res = await _dio!.post('/sync_browsing_history?on_conflict=illust_id', data: {
        'illust_id': h.id,
        'data': {
          'id': h.id,
          'imgPath': h.imgPath,
          'time': h.time.toIso8601String(),
          'imageCount': h.imageCount,
          'isR18': h.isR18 ? 1 : 0,
          'isR18G': h.isR18G ? 1 : 0,
          'isAi': h.isAi ? 1 : 0,
          'isGif': h.isGif ? 1 : 0,
          'width': h.width,
          'height': h.height,
        },
        'updated_at': now,
      }, options: Options(headers: {'Prefer': 'resolution=merge-duplicates'}));
      if (!_ok(res)) {
        Log.error("Sync", "Push browsing history failed: ${res.statusCode}");
        continue;
      }
      onProgress?.call("Pushing browsing history", i + 1, local.length);
    }
  }

  Future<void> _upsertDevice() async {
    if (_stopped) return;
    final now = DateTime.now().toIso8601String();
    final res = await _dio!.post('/sync_devices', data: {
      'device_id': _deviceId,
      'device_name': deviceName,
      'last_sync_at': now,
    }, options: Options(headers: {'Prefer': 'resolution=merge-duplicates'}));
    if (!_ok(res)) {
      Log.error("Sync", "Upsert device failed: ${res.statusCode}");
    }
  }

  Future<List<Map<String, dynamic>>> getDevices() async {
    if (!_ensureDio()) return [];
    try {
      final res = await _dio!.get(
        '/sync_devices',
        queryParameters: {
          'select': 'device_id,device_name,last_sync_at,inserted_at',
          'order': 'last_sync_at.desc',
        },
      );
      lastStatusCode = res.statusCode;
      if (!_ok(res) || res.data == null) return [];
      return (res.data as List).cast<Map<String, dynamic>>();
    } catch (_) {
      return [];
    }
  }

  Future<Map<String, int>> getLocalCounts() async {
    return {
      'searchHistory': appdata.getSearchHistory().length,
      'browsingHistory': HistoryManager().length,
    };
  }

  Future<bool> clearRemoteData() async {
    if (!_ensureDio()) return false;
    final results = await Future.wait([
      _dio!.delete('/sync_search_history'),
      _dio!.delete('/sync_browsing_history'),
      _dio!.delete('/sync_settings?id=eq.1'),
      _dio!.delete('/sync_devices?device_id=neq.$_deviceId'),
    ]);
    return results.every((r) => _ok(r));
  }
}

final syncService = SyncService();
